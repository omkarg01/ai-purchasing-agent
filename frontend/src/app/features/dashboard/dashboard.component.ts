export class DashboardComponent implements OnInit {
  private readonly recommendationService = inject(RecommendationService);

  readonly recommendations = signal<RecommendationResponse[]>([]);
  readonly loading = signal<boolean>(false);
  readonly errorMessage = signal<string | null>(null);

  ngOnInit(): void {
    this.loadRecommendations();
  }

  loadRecommendations(): void {
    this.loading.set(true);
    this.errorMessage.set(null);

    this.recommendationService.list().subscribe({
      next: (data) => {
        this.recommendations.set(data);
        this.loading.set(false);
      },
      error: (err) => {
        this.loading.set(false);
        this.errorMessage.set(err.message || 'Error communicating with backend API.');
      }
    });
  }

  countPending(): number {
    return this.recommendations().filter(r => r.status === 'PENDING_APPROVAL').length;
  }

  countApproved(): number {
    return this.recommendations().filter(r => r.status === 'APPROVED').length;
  }

  countEvaluated(): number {
    return this.recommendations().filter(r => !!r.agent_decision).length;
  }
}

